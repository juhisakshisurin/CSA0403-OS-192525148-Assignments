#!/usr/bin/env python3
"""Estimate B4 application replicas from measured B3 per-container throughput."""
import argparse
import math

def main():
    parser = argparse.ArgumentParser(
        description="Estimate result-portal replicas for 150,000 logins in two hours."
    )
    parser.add_argument("--measured-rps", type=float, required=True,
                        help="Measured sustainable requests/second for ONE app container from B3.")
    parser.add_argument("--requests-per-login", type=float, default=5.0,
                        help="Average backend HTTP requests generated by one login (measure/justify).")
    parser.add_argument("--burst-factor", type=float, default=2.0,
                        help="Peak-to-average arrival multiplier (planning assumption).")
    parser.add_argument("--headroom", type=float, default=1.25,
                        help="Capacity safety factor (planning assumption).")
    parser.add_argument("--students", type=int, default=150000)
    parser.add_argument("--window-hours", type=float, default=2.0)
    parser.add_argument("--base-replicas", type=int, default=3)
    parser.add_argument("--portal-cpu-request", type=float, default=0.25)
    parser.add_argument("--portal-memory-request-mib", type=float, default=256)
    args = parser.parse_args()

    if min(args.measured_rps, args.requests_per_login, args.burst_factor,
           args.headroom, args.window_hours) <= 0:
        parser.error("Throughput, requests/login, factors and window must be positive.")

    duration = args.window_hours * 3600
    average_logins = args.students / duration
    average_http_rps = average_logins * args.requests_per_login
    peak_http_rps = average_http_rps * args.burst_factor
    design_rps = peak_http_rps * args.headroom

    replicas = math.ceil(design_rps / args.measured_rps)
    replicas = max(1, replicas)
    request_cpu = replicas * args.portal_cpu_request
    request_mem = replicas * args.portal_memory_request_mib
    limit_cpu = replicas * 0.50
    limit_mem = replicas * 512

    print("B4 CAPACITY ESTIMATE")
    print(f"Students: {args.students:,}")
    print(f"Login window (hours): {args.window_hours:g}")
    print(f"Average login arrival: {average_logins:.2f} logins/s")
    print(f"Requests per login (assumption/input): {args.requests_per_login:g}")
    print(f"Average backend request rate: {average_http_rps:.2f} requests/s")
    print(f"Burst factor: {args.burst_factor:g}")
    print(f"Peak planning request rate: {peak_http_rps:.2f} requests/s")
    print(f"Headroom factor: {args.headroom:g}")
    print(f"Design target: {design_rps:.2f} requests/s")
    print(f"Measured sustainable rate per container: {args.measured_rps:.2f} requests/s")
    print(f"Required portal replicas: ceil({design_rps:.2f}/{args.measured_rps:.2f}) = {replicas}")
    print(f"Portal CPU request total: {request_cpu:.2f} vCPU")
    print(f"Portal memory request total: {request_mem/1024:.2f} GiB")
    print(f"Portal CPU limit total: {limit_cpu:.2f} vCPU")
    print(f"Portal memory limit total: {limit_mem/1024:.2f} GiB")
    if replicas < args.base_replicas:
        print(f"Note: configured baseline ({args.base_replicas}) exceeds calculated replicas.")
    print("Replace all assumptions with values justified by B3 measurements and traffic traces.")

if __name__ == "__main__":
    main()
